/**
 * Filter and pick real places based on the 4 mandatory user preferences
 */
export function matchPlacesForQuest(
  mood: string,
  timeDuration: string,
  budget: string,
  group: string
): JeddahLocation[] {
  let filtered = JEDDAH_LOCATIONS.filter((place) => {
    // Check group compatibility
    if (!place.suitableGroups.includes(group as any)) return false;

    // Check budget compatibility
    if (budget === 'free' && place.typicalCostSAR > 0) return false;
    if (budget === 'low' && place.typicalCostSAR > 40) return false;
    if (budget === 'medium' && place.typicalCostSAR > 80) return false;

    return true;
  });

  // Prioritize mood matching
  const moodMatched = filtered.filter((place) => place.suitableMoods.includes(mood as any));
  if (moodMatched.length >= 2) {
    filtered = moodMatched;
  }

  // Determine how many steps make sense for the selected time
  let stepCount = 2;
  if (timeDuration === '30m') stepCount = 1;
  else if (timeDuration === '1h') stepCount = 2;
  else if (timeDuration === '2h') stepCount = 2;
  else if (timeDuration === 'half_day') stepCount = 3;
  else if (timeDuration === 'full_day') stepCount = 4;

  // Fallback if not enough places
  if (filtered.length === 0) {
    filtered = JEDDAH_LOCATIONS.filter((p) => budget !== 'free' || p.typicalCostSAR === 0);
  }

  // Shuffle intelligently to give varied quests
  const shuffled = [...filtered].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(stepCount, shuffled.length));
}
